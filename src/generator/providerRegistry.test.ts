/**
 * Task 4.8: Provider Registry and Fallback Tests.
 * 
 * Tests that:
 * - Provider fallback works when primary is unavailable
 * - Mock provider is used as final fallback
 * - Error messages are clear
 * - Provider status can be queried
 */

import { describe, it, expect, beforeEach } from 'vitest'
import { ProviderRegistry } from './providerRegistry'
import { ModelProvider, ScriptGenRequest, ScriptGenResponse } from './modelProvider'

class FailingProvider extends ModelProvider {
  name = 'Failing Provider'

  async generate(request: ScriptGenRequest): Promise<ScriptGenResponse> {
    throw new Error('Provider is misconfigured')
  }

  async isAvailable(): Promise<boolean> {
    return false
  }
}

class WorkingProvider extends ModelProvider {
  name = 'Working Provider'

  async generate(request: ScriptGenRequest): Promise<ScriptGenResponse> {
    return {
      code: `on mouseUp
  answer "Generated by working provider"
end mouseUp`,
      explanation: 'Generated successfully',
      confidence: 0.95
    }
  }

  async isAvailable(): Promise<boolean> {
    return true
  }
}

class UnavailableProvider extends ModelProvider {
  name = 'Unavailable Provider'

  async generate(request: ScriptGenRequest): Promise<ScriptGenResponse> {
    return {
      code: 'This should not be called',
      confidence: 0.0
    }
  }

  async isAvailable(): Promise<boolean> {
    return false
  }
}

describe('Task 4.8: Provider Registry and Fallback', () => {
  let registry: ProviderRegistry

  beforeEach(() => {
    registry = new ProviderRegistry()
  })

  it('uses first available provider', async () => {
    registry.register(new WorkingProvider())
    registry.register(new UnavailableProvider())

    const result = await registry.generate({
      description: 'test',
      context: {}
    })

    expect('code' in result).toBe(true)
    if ('code' in result) {
      expect(result.code).toContain('working provider')
    }
  })

  it('skips unavailable providers and uses fallback', async () => {
    registry.register(new UnavailableProvider())
    registry.register(new WorkingProvider())

    const result = await registry.generate({
      description: 'test',
      context: {}
    })

    expect('code' in result).toBe(true)
    if ('code' in result) {
      expect(result.code).toContain('working provider')
    }
  })

  it('falls back to mock provider when all registered fail', async () => {
    registry.register(new FailingProvider())
    registry.register(new UnavailableProvider())

    const result = await registry.generate({
      description: 'click button',
      context: {}
    })

    expect('code' in result).toBe(true)
    if ('code' in result) {
      expect(result.code).toContain('on mouseUp')
    }
  })

  it('reports error message when generation fails completely', async () => {
    registry.register(new FailingProvider())

    const result = await registry.generate({
      description: 'test',
      context: {}
    })

    // With mock fallback, should not error
    expect('code' in result).toBe(true)
  })

  it('provides status of all providers', async () => {
    registry.register(new WorkingProvider())
    registry.register(new UnavailableProvider())

    const status = await registry.getProvidersStatus()

    expect(status.length).toBeGreaterThanOrEqual(2)
    expect(status.some(s => s.name === 'Working Provider' && s.available)).toBe(true)
    expect(status.some(s => s.name === 'Unavailable Provider' && !s.available)).toBe(true)
    expect(status.some(s => s.name === 'Mock Provider (Local)')).toBe(true)
  })

  it('clears registered providers', async () => {
    registry.register(new WorkingProvider())
    registry.clear()

    const result = await registry.generate({
      description: 'test',
      context: {}
    })

    // Should use mock provider
    expect('code' in result).toBe(true)
  })

  it('uses mock provider template matching', async () => {
    registry.clear() // Clear any registered providers

    const result = await registry.generate({
      description: 'when the user clicks, show an alert',
      context: {}
    })

    expect('code' in result).toBe(true)
    if ('code' in result) {
      expect(result.code).toContain('on mouseUp')
      expect(result.code).toContain('answer')
    }
  })
})
