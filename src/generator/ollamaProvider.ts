/**
 * Task 4.3: OllamaProvider for local Ollama instance.
 * 
 * Implements BYOK (Bring Your Own Key) for local Ollama.
 * Fetch to http://localhost:11434/api/generate (configurable)
 * 
 * No API key needed; runs locally.
 * Falls back gracefully if Ollama is not running.
 */

import { ModelProvider, ScriptGenRequest, ScriptGenResponse } from './modelProvider'

export class OllamaProvider extends ModelProvider {
  name = 'Ollama (Local)'
  
  private baseUrl: string = 'http://localhost:11434'
  private model: string = 'mistral' // Common default model for Ollama
  private timeout: number = 60000 // 60 seconds (local requests can take longer)
  
  /**
   * Set the base URL for Ollama (e.g., http://192.168.1.100:11434).
   */
  setBaseUrl(url: string): void {
    this.baseUrl = url
  }
  
  getBaseUrl(): string {
    return this.baseUrl
  }
  
  /**
   * Set the model name (e.g., 'mistral', 'neural-chat', 'llama2').
   */
  setModel(model: string): void {
    this.model = model
  }
  
  getModel(): string {
    return this.model
  }
  
  async isAvailable(): Promise<boolean> {
    // Try to reach Ollama's API
    try {
      const controller = new AbortController()
      const timeoutId = setTimeout(() => controller.abort(), 5000) // 5s timeout for availability check
      
      // Ollama has a /api/tags endpoint that lists available models
      const response = await fetch(`${this.baseUrl}/api/tags`, {
        method: 'GET',
        signal: controller.signal
      })
      
      clearTimeout(timeoutId)
      
      return response.ok
    } catch (err) {
      // Ollama not running or unreachable
      return false
    }
  }
  
  async generate(request: ScriptGenRequest): Promise<ScriptGenResponse> {
    // Build prompt
    const prompt = this.buildPrompt(request)
    
    try {
      const controller = new AbortController()
      const timeoutId = setTimeout(() => controller.abort(), this.timeout)
      
      const response = await fetch(`${this.baseUrl}/api/generate`, {
        method: 'POST',
        headers: {
          'content-type': 'application/json'
        },
        body: JSON.stringify({
          model: this.model,
          prompt,
          stream: false,
          raw: true // Bypass templating
        }),
        signal: controller.signal
      })
      
      clearTimeout(timeoutId)
      
      if (!response.ok) {
        if (response.status === 404) {
          throw new Error(`Ollama model "${this.model}" not found. Install it with: ollama pull ${this.model}`)
        }
        throw new Error(`Ollama API error: HTTP ${response.status}`)
      }
      
      const data = await response.json() as { response?: string }
      const generated = data.response || ''
      
      if (!generated) {
        throw new Error('Ollama returned empty response')
      }
      
      return {
        code: generated.trim(),
        explanation: `Generated by Ollama using ${this.model}`,
        confidence: 0.7
      }
    } catch (err) {
      if (err instanceof Error && err.name === 'AbortError') {
        throw new Error('Request timeout: Ollama took too long to respond. The server may be overloaded.')
      }
      if (err instanceof Error && err.message.includes('Failed to fetch')) {
        throw new Error('Ollama not running. Start it with: ollama serve')
      }
      throw err
    }
  }
  
  private buildPrompt(request: ScriptGenRequest): string {
    const systemPrompt = `You are a HyperTalk code generator. Generate ONLY valid HyperTalk code in response to user requests.
    
Your response must be:
1. ONLY the handler definition (no explanations, no markdown, no code blocks)
2. Valid HyperTalk syntax
3. Wrapped in "on HANDLER_NAME ... end HANDLER_NAME" format

Example format:
on mouseUp
  answer "Hello world"
end mouseUp

Never include explanations or anything except the code.`
    
    const userPart = this.buildUserMessage(request)
    
    return `${systemPrompt}\n\nUser request:\n${userPart}`
  }
  
  private buildUserMessage(request: ScriptGenRequest): string {
    const parts: string[] = [request.description]
    
    if (request.context.cardName) {
      parts.push(`Card: ${request.context.cardName}`)
    }
    if (request.context.fieldNames && request.context.fieldNames.length > 0) {
      parts.push(`Available fields: ${request.context.fieldNames.join(', ')}`)
    }
    if (request.context.buttonLabels && request.context.buttonLabels.length > 0) {
      parts.push(`Available buttons: ${request.context.buttonLabels.join(', ')}`)
    }
    
    return parts.join('\n')
  }
}
